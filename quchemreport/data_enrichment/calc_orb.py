def CDFT_plus_Indices(data_model_opt: LogData, data_model_spplus: LogData):
    Eref = data_model_opt.results.wavefunction.total_molecular_energy
    Eplus = data_model_spplus.results.wavefunction.total_molecular_energy
    Mulliken_partial_charges_opt = data_model_opt.results.wavefunction.Mulliken_partial_charges
    Mulliken_partial_charges_spplus = data_model_spplus.results.wavefunction.Mulliken_partial_charges
    Hirshfeld_partial_charges_opt = data_model_opt.results.wavefunction.Hirshfeld_partial_charges
    Hirshfeld_partial_charges_spplus = data_model_spplus.results.wavefunction.Hirshfeld_partial_charges

    # Check if all necessary data is available
    if (
      Eref is None
      or Eplus is None
      or Mulliken_partial_charges_opt is None
      or Mulliken_partial_charges_spplus is None
    ):
      return None, None, None

    # total_molecular_energy is in hartree (scanlog converts the cclib eV values); A in eV
    A = (Eref-Eplus) * Eh_to_eV

    OPT_charges = np.array(Mulliken_partial_charges_opt)
    SPplus_charges = np.array(Mulliken_partial_charges_spplus)
    fplus_lambda_mulliken = np.subtract(OPT_charges, SPplus_charges)

    if Hirshfeld_partial_charges_opt != None:
      OPT_charges = np.array(Hirshfeld_partial_charges_opt)
    else:
      OPT_charges = []
    
    if Hirshfeld_partial_charges_spplus != None:
      SPplus_charges = np.array(Hirshfeld_partial_charges_spplus)
    else:
      SPplus_charges = []
    
    fplus_lambda_hirshfeld = np.subtract(OPT_charges, SPplus_charges)

    return A, fplus_lambda_mulliken, fplus_lambda_hirshfeld
    #return A, fplus_lambda_mulliken


