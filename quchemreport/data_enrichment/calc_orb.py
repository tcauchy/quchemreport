def _mo_index(label, homo):
    """Zero-based MO index from an int or a label such as 'homo', 'lumo+2' (orbkit syntax)."""
    if isinstance(label, (int, np.integer)):
        return int(label)
    m = re.fullmatch(r"(homo|lumo)\s*([+-]\s*\d+)?", str(label).strip().lower())
    if m is None:
        raise ValueError(f"Unsupported MO label {label!r}")
    offset = int(m.group(2).replace(" ", "")) if m.group(2) else 0
    return homo + offset + (1 if m.group(1) == "lumo" else 0)

